"""Initial supported application schema and verified baseline."""

from alembic import op
from alembic.util import CommandError

revision = "0001_initial"
down_revision = None
branch_labels = None
depends_on = None

INITIAL_SCHEMA = """
CREATE TABLE firms (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    balance_cents INTEGER NOT NULL CHECK (balance_cents >= 0),
    uuid TEXT NOT NULL CHECK (uuid::uuid::text = uuid)
);

-- A unique B-tree index makes public UUID lookups efficient and unambiguous.
CREATE UNIQUE INDEX firms_uuid_idx ON firms (uuid);

CREATE TABLE payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer_firm_id INTEGER NOT NULL REFERENCES firms (id),
    payee_firm_id INTEGER NOT NULL REFERENCES firms (id),
    amount_cents INTEGER NOT NULL CHECK (amount_cents > 0),
    description TEXT NOT NULL,
    CHECK (payer_firm_id <> payee_firm_id)
);

-- No FK to firms: durable responses include unknown-firm rejections, and an
-- idempotency reservation must not acquire firm locks before the sorted lock set.
CREATE TABLE bulk_payment_requests (
    payer_firm_uuid TEXT NOT NULL,
    idempotency_key TEXT COLLATE "C" NOT NULL CHECK (length(idempotency_key) BETWEEN 1 AND 128),
    request_fingerprint TEXT NOT NULL CHECK (length(request_fingerprint) = 64),
    status_code INTEGER CHECK (status_code IN (201, 422)),
    response_body JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (payer_firm_uuid, idempotency_key),
    CHECK ((status_code IS NULL) = (response_body IS NULL))
);
"""


def upgrade() -> None:
    connection = op.get_bind()
    present = connection.exec_driver_sql(
        "SELECT to_regclass('firms'), to_regclass('payments'), to_regclass('bulk_payment_requests')"
    ).one()
    if any(present):
        # This first slice rejects legacy data until verified adoption is delivered.
        raise CommandError("Unversioned application schema requires verified adoption")
    connection.exec_driver_sql(INITIAL_SCHEMA)


def downgrade() -> None:
    raise CommandError("Destructive initial downgrade is unsupported")
