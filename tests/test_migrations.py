def test_lifecycle_preserves_legacy_and_starts_full_ttl(database_url):
    from psycopg.types.json import Jsonb

    with new_database(database_url) as url:
        install_previous_schema(url)
        with psycopg.connect(url) as connection:
            connection.execute((ROOT / "examples/firms.sql").read_text())
            connection.execute(
                "INSERT INTO payments (payer_firm_id,payee_firm_id,amount_cents,description) "
                "VALUES (1,2,100,'retained')"
            )
            # A valid historical envelope is preserved exactly, not regenerated by migration.
            response = {
                "payments_created": 1,
                "total_amount_cents": 100,
                "payments": [
                    {
                        "id": 1,
                        "payer_firm_uuid": "3f1c9a2e-7b4d-4c1e-9a55-2d8e6f0b7c41",
                        "payee_firm_uuid": "8b2e4c71-0d3a-4f6e-b1c9-5a7d2e9f4c10",
                        "amount_cents": 100,
                        "description": "retained",
                    }
                ],
            }
            for key, status, body in [
                ("success", 201, response),
                ("decline", 422, {"detail": "insufficient_funds"}),
            ]:
                connection.execute(
                    "INSERT INTO bulk_payment_requests VALUES "
                    "(%s,%s,%s,%s,%s,now()-interval '1 year')",
                    ("3f1c9a2e-7b4d-4c1e-9a55-2d8e6f0b7c41", key, "a" * 64, status, Jsonb(body)),
                )
            started = connection.execute("SELECT clock_timestamp()").fetchone()[0]
        before = state(url)
        migrate(url)
        after = state(url)
        assert after["rows"]["firms"] == before["rows"]["firms"]
        assert after["rows"]["payments"] == before["rows"]["payments"]
        assert after["sequences"] == before["sequences"]
        assert [row[:6] for row in after["rows"]["bulk_payment_requests"]] == before["rows"][
            "bulk_payment_requests"
        ]
        with psycopg.connect(url) as connection:
            rows = connection.execute(
                "SELECT state, completed_at,expires_at-completed_at,created_at<completed_at "
                "FROM bulk_payment_requests"
            ).fetchall()
            from datetime import timedelta

            assert all(
                r[0] == "completed" and r[1] >= started and r[2] == timedelta(hours=24) and r[3]
                for r in rows
            )
            assert connection.execute(
                "SELECT count(DISTINCT completed_at) FROM bulk_payment_requests"
            ).fetchone() == (1,)
            assert connection.execute(
                "SELECT count(*) FROM request_result_receipts r JOIN bulk_payment_requests b "
                "USING(generation) WHERE r.status_code=b.status_code "
                "AND r.response_body=b.response_body "
                "AND r.request_fingerprint=b.request_fingerprint AND r.owner_token=b.owner_token"
            ).fetchone() == (2,)
            assert connection.execute(
                "SELECT count(*) FROM request_execution_guards"
            ).fetchone() == (2,)


