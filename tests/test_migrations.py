def install_previous_schema(url):
    """The immutable former revision is an independent legacy input, not current DDL."""
    previous = ScriptDirectory.from_config(migration_config()).get_revision("0001_initial")
    with psycopg.connect(url) as connection:
        connection.execute(previous.module.INITIAL_SCHEMA)
        connection.execute("CREATE TABLE alembic_version (version_num VARCHAR(32) PRIMARY KEY)")
        connection.execute("INSERT INTO alembic_version VALUES ('0001_initial')")


