def test_lifecycle_partial_upgrade_rolls_back(database_url):
    with new_database(database_url) as url:
        install_previous_schema(url)
        with psycopg.connect(url) as connection:
            connection.execute("""
                CREATE FUNCTION fail_lifecycle() RETURNS event_trigger LANGUAGE plpgsql AS $$
                BEGIN
                    IF to_regclass('request_result_receipts') IS NOT NULL THEN
                        RAISE EXCEPTION 'synthetic lifecycle migration failure';
                    END IF;
                END $$;
                CREATE EVENT TRIGGER lifecycle_fault ON ddl_command_end
                WHEN TAG IN ('CREATE TABLE') EXECUTE FUNCTION fail_lifecycle();
            """)
        before = state(url)
        with pytest.raises(CommandError):
            migrate(url)
        assert state(url) == before
        with psycopg.connect(url) as connection:
            assert connection.execute(
                "SELECT to_regclass('request_execution_guards')"
            ).fetchone() == (None,)
            connection.execute("DROP EVENT TRIGGER lifecycle_fault; DROP FUNCTION fail_lifecycle()")
        migrate(url)
        assert state(url)["versions"] == [("0002_request_lifecycle",)]


@contextmanager
def new_database(base_url):
    name = "migration_" + uuid.uuid4().hex
    parsed = urlsplit(base_url)
    url = urlunsplit(parsed._replace(path="/" + name))
    with psycopg.connect(base_url, autocommit=True, connect_timeout=3) as admin:
        admin.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(name)))
        try:
            yield url
        finally:
            admin.execute(sql.SQL("DROP DATABASE {} WITH (FORCE)").format(sql.Identifier(name)))


def head():
    return ScriptDirectory.from_config(migration_config()).get_current_head()


def state(url):
    with psycopg.connect(url, connect_timeout=3) as connection:
        present = connection.execute(
            "SELECT to_regclass('alembic_version'), to_regclass('firms'), "
            "to_regclass('payments'), to_regclass('bulk_payment_requests')"
        ).fetchone()
        versions = (
            connection.execute(
                "SELECT version_num FROM alembic_version ORDER BY version_num"
            ).fetchall()
            if present[0]
            else []
        )
        rows = {}
        sequences = {}
        for table, exists in zip(
            ["firms", "payments", "bulk_payment_requests"], present[1:], strict=True
        ):
            if exists:
                rows[table] = connection.execute(
                    sql.SQL("SELECT * FROM {} ORDER BY 1,2").format(sql.Identifier(table))
                ).fetchall()
        for table in ["firms", "payments"]:
            if present[1 if table == "firms" else 2]:
                sequence = connection.execute(
                    "SELECT pg_get_serial_sequence(%s,'id')", (table,)
                ).fetchone()[0]
                if sequence:
                    # PostgreSQL supplies this qualified identifier, not request data.
                    sequences[table] = connection.execute(
                        sql.SQL("SELECT last_value,is_called FROM {}").format(
                            sql.Identifier(*sequence.split("."))
                        )
                    ).fetchone()
        structure = connection.execute(
            "SELECT c.relname,a.attname,format_type(a.atttypid,a.atttypmod),"
            "a.attnotnull,a.attidentity,pg_get_expr(d.adbin,d.adrelid) "
            "FROM pg_class c JOIN pg_attribute a ON a.attrelid=c.oid "
            "LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum "
            "WHERE c.relnamespace=current_schema()::regnamespace "
            "AND c.relname IN ('firms','payments','bulk_payment_requests') "
            "AND a.attnum>0 AND NOT a.attisdropped ORDER BY c.relname,a.attnum"
        ).fetchall()
        constraints = connection.execute(
            "SELECT c.relname,pg_get_constraintdef(x.oid),x.convalidated FROM pg_class c "
            "JOIN pg_constraint x ON x.conrelid=c.oid "
            "WHERE c.relnamespace=current_schema()::regnamespace "
            "AND c.relname IN ('firms','payments','bulk_payment_requests') ORDER BY 1,2"
        ).fetchall()
        indexes = connection.execute(
            "SELECT tablename,indexname,indexdef FROM pg_indexes "
            "WHERE schemaname=current_schema() "
            "AND tablename IN ('firms','payments','bulk_payment_requests') ORDER BY 1,2"
        ).fetchall()
        return {
            "relations": present,
            "versions": versions,
            "rows": rows,
            "sequences": sequences,
            "schema": (structure, constraints, indexes),
        }


def seed_history(url):
    """Independent retained-history fixture, usable before the new HTTP writer is delivered."""
    from psycopg.types.json import Jsonb

    from app.schemas.payments import BulkPayment

    body = json.loads((ROOT / "examples/bulk-payment.json").read_text())
    request = BulkPayment.model_validate(body)
    response = {
        "payments_created": len(request.payments),
        "total_amount_cents": request.total_cents,
        "payments": [],
    }
    with psycopg.connect(url) as connection:
        connection.execute((ROOT / "examples/firms.sql").read_text())
        connection.execute(
            "UPDATE firms SET balance_cents=balance_cents-%s WHERE id=1", (request.total_cents,)
        )
        for payment in request.payments:
            payee = connection.execute(
                "SELECT id FROM firms WHERE uuid=%s", (str(payment.payee_firm_uuid),)
            ).fetchone()[0]
            connection.execute(
                "UPDATE firms SET balance_cents=balance_cents+%s WHERE id=%s",
                (payment.amount_cents, payee),
            )
            identifier = connection.execute(
                "INSERT INTO payments(payer_firm_id,payee_firm_id,amount_cents,description) "
                "VALUES (1,%s,%s,%s) RETURNING id",
                (payee, payment.amount_cents, payment.description),
            ).fetchone()[0]
            response["payments"].append(
                {
                    "id": identifier,
                    "payer_firm_uuid": str(request.payer_firm_uuid),
                    "payee_firm_uuid": str(payment.payee_firm_uuid),
                    "amount_cents": payment.amount_cents,
                    "description": payment.description,
                }
            )
        modern = connection.execute("SELECT to_regclass('request_execution_guards')").fetchone()[0]
        if modern:
            generation, owner = uuid.uuid4(), uuid.uuid4()
            connection.execute(
                "INSERT INTO bulk_payment_requests(payer_firm_uuid,idempotency_key,"
                "request_fingerprint,status_code,response_body,state,generation,owner_token,"
                "owner_deadline,completed_at,expires_at) VALUES (%s,'migration-retained',%s,201,%s,"
                "'completed',%s,%s,now(),now(),now()+interval '24 hours')",
                (
                    str(request.payer_firm_uuid),
                    request.fingerprint(),
                    Jsonb(response),
                    generation,
                    owner,
                ),
            )
            connection.execute(
                "INSERT INTO request_execution_guards VALUES (%s,%s,'migration-retained')",
                (generation, str(request.payer_firm_uuid)),
            )
            connection.execute(
                "INSERT INTO request_result_receipts(generation,owner_token,request_fingerprint,"
                "status_code,response_body) VALUES (%s,%s,%s,201,%s)",
                (generation, owner, request.fingerprint(), Jsonb(response)),
            )
        else:
            connection.execute(
                "INSERT INTO bulk_payment_requests(payer_firm_uuid,idempotency_key,"
                "request_fingerprint,status_code,response_body) "
                "VALUES (%s,'migration-retained',%s,201,%s)",
                (str(request.payer_firm_uuid), request.fingerprint(), Jsonb(response)),
            )
    return body, response


def empty_upgrade(url):
    migrate(url)
    value = state(url)
    assert value["versions"] == [(head(),)]
    assert len(value["rows"]) == 3 and all(not rows for rows in value["rows"].values())


def repeat_upgrade(url):
    migrate(url)
    seed_history(url)
    before = state(url)
    migrate(url)
    assert state(url) == before


def failed_upgrade(url):
    install_fault(url)
    try:
        with pytest.raises(CommandError):
            migrate(url)
        assert state(url)["relations"] == (None, None, None, None)
    finally:
        remove_fault(url)
    empty_upgrade(url)


def rejected_downgrade(url):
    migrate(url)
    seed_history(url)
    before = state(url)
    with pytest.raises(CommandError):
        command.downgrade(migration_config(url), "base")
    assert state(url) == before


